SCAN_ROOTS = ["cassandra_ns", "scripts", "tests", "notebooks"]
SCAN_FILES = ["README.md", "config.yaml", "Makefile", "Dockerfile",
              "requirements.txt"]


@pytest.fixture(scope="session")
def config() -> dict:
    raw = (REPO_ROOT / "config.yaml").read_text(encoding="utf-8")
    return yaml.safe_load(raw)


def test_required_tree() -> None:
    missing = [rel for rel in REQUIRED_TREE
               if not (REPO_ROOT / rel).is_file()]
    assert not missing, f"required files missing: {missing}"


def test_seed(config: dict) -> None:
    assert config["seed"] == 42, "every random decision is pinned to seed 42"


def test_models_contract(config: dict) -> None:
    models = {m["name"]: m["layers"] for m in config["models"]}
    assert set(models) == {"gpt2", "pythia-410m"}
    assert models["gpt2"] == [2, 5, 8, 11]
    assert models["pythia-410m"] == [5, 11, 17, 23]


def test_data_keys(config: dict) -> None:
    data = config["data"]
    for key in ("tf_base_url", "tf_filename_template", "domains",
                "trivias_n", "cache_dir"):
        assert key in data, f"config.data missing key: {key}"
    assert data["trivias_n"] > 0
    assert "{domain}" in data["tf_filename_template"]


def test_splits_contract(config: dict) -> None:
    splits = config["splits"]
    assert splits["group_by"] == "entity", \
        "splits MUST group by entity: row-wise splits leak subjects across folds"
    assert splits["stratify_by"] == ["domain", "label"]
    assert splits["n_folds"] >= 2


def test_probes_contract(config: dict) -> None:
    probes = config["probes"]
    assert set(probes["types"]) <= {"logistic", "mlp"}
    assert all(c > 0 for c in probes["C_grid"])
    assert probes["mlp_hidden"] > 0
    assert set(probes["feature_modes"]) == {"last_token", "mean_pool"}


def test_stats_contract(config: dict) -> None:
    stats = config["stats"]
    assert stats["n_bootstrap"] >= 100
    assert 0 < stats["ci"] < 1
    assert stats["multiple_comparison"] == "holm"


def test_generation_and_abstention(config: dict) -> None:
    assert config["generation"]["max_new_tokens"] > 0
    assert config["generation"]["n_prompts"] > 0
    assert 0 < config["abstention"]["min_coverage"] < 1


def test_makefile_targets_declared() -> None:
    text = (REPO_ROOT / "Makefile").read_text(encoding="utf-8")
    declared = set(re.findall(r"^([a-zA-Z_-]+)\s*:", text, flags=re.MULTILINE))
    missing = [t for t in MAKEFILE_TARGETS if t not in declared]
    assert not missing, f"Makefile missing targets: {missing}"


def _iter_scan_targets():
    for root in SCAN_ROOTS:
        base = REPO_ROOT / root
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.suffix in {".py", ".md", ".ipynb", ".yaml", ".yml"} \
                    and path.is_file():
                yield path
    for rel in SCAN_FILES:
        path = REPO_ROOT / rel
        if path.is_file():
            yield path


def test_no_ai_markers() -> None:
    offenders = []
    this_file = Path(__file__).resolve()
    for path in _iter_scan_targets():
        if path.resolve() == this_file:
            continue  # the marker list itself lives here
        text = path.read_text(encoding="utf-8", errors="replace").lower()
        for marker in FORBIDDEN_MARKERS:
            if marker in text:
                rel = path.relative_to(REPO_ROOT)
                offenders.append(f"{rel}: contains '{marker}'")
    assert not offenders, (
        "prohibited attribution markers found:\n" + "\n".join(offenders)
    )
